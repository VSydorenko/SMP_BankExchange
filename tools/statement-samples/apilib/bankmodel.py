"""Модель банку monobank юросіб для синтетичної пагінації: реалізує ЛИШЕ виміряне (журнал 05а, `9e1eb08`, запис
`corp_a1_statement_small_limit`, run1/run2), нічого більше.

Виміряно:
* порядок відповіді -- за спаданням `time` (журнал 05а, «Задача 1, Step 3», пункт 8: усі 33 з 33 від нових до старих);
* запит із `to`, рівним `time` операції, цієї операції НЕ повертає (`9e1eb08`: `to` = `time` останньої операції сторінки, повтору
  межової операції немає, 33 унікальні з 33);
* відповідь обрізається за `limit` (сторінки 10, 10, 10, 3 при `limit=10`).

НЕ виміряно, тому в моделі немає: нижньої межі `from` (синтетичні набори тримають усі операції всередині відрізка), порядку
операцій усередині однієї секунди (береться порядок набору), поведінки при `limit` понад максимум сторінки банку.
"""


class CorpBank:
    def __init__(self, ops, to_inclusive=False):
        """`ops` -- операції (словники StatementItem з `time`), порядок усередині секунди зберігається. `to_inclusive=True` --
        ЗІПСОВАНА модель для контролю (межова секунда повертається): у вимірі вона хибна."""
        self.ops = list(ops)
        self.to_inclusive = to_inclusive

    def statement(self, frm, to, limit):
        """Сторінка відповіді на запит виписки: найновіші `limit` операцій з `time` < `to` (від нових до старих)."""
        below = [o for o in self.ops if (o['time'] <= to if self.to_inclusive else o['time'] < to)]
        return sorted(below, key=lambda o: -o['time'])[:limit]
